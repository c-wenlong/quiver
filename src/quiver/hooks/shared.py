"""The shared hook tier: ``~/.quiver/hooks/shared/<name>.py`` for every harness.

A shared hook is one Python script written against the normalized payload
(``contracts.py`` documents the fields). It declares the events it wants
in a header comment line — ``# events: [PreToolUse, Stop]`` — and the
deploy step generates a thin per-harness wrapper for every installed,
shim-able harness whose event map covers at least one declared event.

The generated pieces all live in the hub, so ``plan_hooks`` links them
like any other script:

  ~/.quiver/hooks/_runtime/shim.py        the payload translator (a copy
                                          of quiver's shim_runtime.py)
  ~/.quiver/hooks/<harness>/_generated/   one stub per shared script; the
                                          directory links whole into the
                                          harness's hooks root, so the
                                          declaration is
                                          ~/.claude/hooks/_generated/x.py

A stub is a few lines with the runtime path, the contract JSON and the
shared source baked in: it feeds its stdin to the runtime and passes the
answer back. The translation lives in the one runtime file so fixes ship
to every harness at once — only the stub's baked defaults differ, which
is why cursor stubs also carry a mandatory JSON fallback for the failure
paths where printing nothing would stall a session.

``swe init`` (and ``swe hooks sync``) runs ``apply_deploy``: write the
runtime and the stubs that changed, and prune any file carrying the
GENERATED marker whose shared source vanished or stopped qualifying.
Everything is idempotent — unchanged files keep their bytes, so a rerun
does not churn mtimes.

Passthrough for grouped-schema harnesses was considered and rejected:
the shared contract's fields (``event``, ``tool_output``, ``raw``) do
not exist in a raw Claude payload, so a script written to the normalized
names would silently read ``None``. Every harness gets the same shim.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path

from quiver import paths as _paths
from quiver.hooks.contracts import CONTRACTS, HookContract, contract_for
from quiver.init.hooks import DISABLED_BASENAME, RESERVED_HUB_DIRS

SHARED_DIRNAME = "shared"
RUNTIME_DIRNAME = "_runtime"
GENERATED_DIRNAME = "_generated"
RUNTIME_BASENAME = "shim.py"
GENERATED_MARK = "GENERATED by quiver"

_EVENTS_RE = re.compile(r"^events\s*:\s*(.+)$", re.IGNORECASE)
_EVENT_NAME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9]*$")
# How many lines count as "the header" for an events declaration.
_HEADER_LINES = 60


def shared_dir(home: Path) -> Path:
    return _paths.hooks_dir_for(home) / SHARED_DIRNAME


def runtime_dir(home: Path) -> Path:
    return _paths.hooks_dir_for(home) / RUNTIME_DIRNAME


def runtime_file(home: Path) -> Path:
    return runtime_dir(home) / RUNTIME_BASENAME


def generated_dir(home: Path, harness: str) -> Path:
    return _paths.hooks_dir_for(home) / harness / GENERATED_DIRNAME


def disabled_file(hub_dir: Path) -> Path:
    """The ``.disabled`` marker beside the scripts it names."""
    return hub_dir / DISABLED_BASENAME


def disabled_names(hub_dir: Path) -> set[str]:
    """Script basenames ``swe hooks disable`` switched off in ``hub_dir``.

    init.hooks._disabled_hook_names reads the same file for plan_hooks;
    this wrapper names it for the domain.
    """
    from quiver.init.hooks import _disabled_hook_names

    return _disabled_hook_names(hub_dir)


def set_disabled(hub_dir: Path, name: str, off: bool) -> None:
    """Add or remove ``name`` in ``hub_dir``'s ``.disabled`` file."""
    names = disabled_names(hub_dir)
    if off:
        names.add(name)
    else:
        names.discard(name)
    marker = disabled_file(hub_dir)
    if not names:
        try:
            marker.unlink()
        except FileNotFoundError:
            pass
        return
    marker.write_text(
        "# hooks swe leaves unlinked — swe hooks enable <name> restores\n"
        + "\n".join(sorted(names)) + "\n",
        encoding="utf-8")


def shared_scripts(home: Path) -> list[Path]:
    """Every ``*.py`` directly under hooks/shared/, sorted."""
    root = shared_dir(home)
    if not root.is_dir():
        return []
    return sorted(
        entry for entry in root.iterdir()
        if entry.is_file() and entry.suffix == ".py"
        and not entry.name.startswith("."))


def script_events(path: Path, limit: int = _HEADER_LINES) -> list[str]:
    """The events one shared script declares in its header, or [].

    The first ``events:``-looking line in the leading comment/docstring
    block wins. Both ``events: [A, B]`` and ``events: A, B`` parse;
    tokens that are not event names are dropped, so a prose line like
    ``events: see the docstring`` reads as undeclared rather than garbage.
    """
    try:
        lines = path.read_text(
            encoding="utf-8", errors="replace").splitlines()[:limit]
    except OSError:
        return []
    for raw in lines:
        line = raw.strip().lstrip("#").strip()
        match = _EVENTS_RE.match(line)
        if not match:
            continue
        value = match.group(1).strip()
        if value.startswith("[") and value.endswith("]"):
            value = value[1:-1]
        return [token for token in
                (part.strip() for part in value.split(","))
                if _EVENT_NAME_RE.fullmatch(token)]
    return []


@dataclass(frozen=True)
class DeployTarget:
    """One generated wrapper: shared ``source`` shimmed for ``harness``."""

    harness: str
    source: Path
    wrapper: Path            # ~/.quiver/hooks/<harness>/_generated/<name>
    covered: tuple[str, ...]  # native events whose normalized name is declared


def _harness_installed(root: Path, name: str, registry: dict, home: Path) -> bool:
    """Same evidence rule plan_hooks uses: the dir, or the binary on PATH."""
    from quiver.init.hooks import command_on_path
    from quiver.init.layout import HARNESS_SIGNATURES, harness_installed

    if root.is_dir():
        return True
    if root.parent != home and root.parent.is_dir():
        return True
    return harness_installed(
        name, HARNESS_SIGNATURES.get(name), home, registry) \
        or command_on_path(name, registry)


def _candidate_names(registry: dict) -> list[str]:
    """Every name a shared hook could deploy to, contract or registry."""
    return sorted(set(CONTRACTS) | set(registry))


def deploy_targets(
    home: Path, registry: dict | None = None, *,
    include_disabled: bool = False,
) -> list[DeployTarget]:
    """The wrappers the shared tier wants on this machine, fully resolved.

    For every enabled shared script x every installed shim-able harness
    whose event map covers at least one declared event. A script with no
    ``events:`` header deploys nowhere — the header is the opt-in — and
    neither does a disabled one. ``include_disabled`` is the inventory's
    view: it still lists the row, marked disabled. Archived harnesses are
    unmanaged, the same rule ``plan_hooks`` keeps.
    """
    from quiver.init.layout import archived_names, load_registry

    if registry is None:
        registry = load_registry(home)
    archived = archived_names(registry)
    targets: list[DeployTarget] = []
    for script in shared_scripts(home):
        if not include_disabled \
                and script.name in disabled_names(shared_dir(home)):
            continue
        declared = set(script_events(script))
        if not declared:
            continue
        for name in _candidate_names(registry):
            if name in archived:
                continue
            contract = contract_for(registry, name, home)
            if not contract.shim_able:
                continue
            # Table roots are home-relative; left bare they resolve
            # against the cwd, so a project's .claude/ read as an install.
            root = None if contract.root is None else home / contract.root
            if root is None or not _harness_installed(
                    root, name, registry, home):
                continue
            covered = tuple(
                native for native, normalized
                in zip(contract.events, contract.normalized_events())
                if normalized in declared)
            if not covered:
                continue
            targets.append(DeployTarget(
                name, script, generated_dir(home, name) / script.name,
                covered))
    return targets


# --- generation ------------------------------------------------------------


RUNTIME_SOURCE = Path(__file__).parent / "shim_runtime.py"


def runtime_text() -> str:
    """The shim runtime file's contents: banner + the shipped source."""
    source = RUNTIME_SOURCE.read_text(encoding="utf-8")
    return (
        "# " + GENERATED_MARK + " — do not edit.\n"
        "# Source: src/quiver/hooks/shim_runtime.py in the quiver package.\n"
        + source)


def _contract_json(harness: str, contract: HookContract) -> str:
    """The contract slice a generated stub bakes for the runtime."""
    return json.dumps({
        "harness": harness,
        "schema": contract.schema,
        "event_map": contract.event_map,
        "fields": contract.fields,
        "must_print_json": contract.must_print_json,
    }, sort_keys=True, separators=(",", ":"))


def _stub_default(contract: HookContract) -> str:
    """The JSON a must-print stub emits when the runtime cannot answer.

    Cursor's flat schema reads ``permission`` on pre*/before* events and
    ``continue`` elsewhere, so the union object satisfies both. Grouped
    must-print contracts (gemini, qwen) want a bare ``{}``. Contracts
    that tolerate silence get "", which prints nothing.
    """
    if not contract.must_print_json:
        return ""
    if contract.schema == "flat":
        return '{"permission": "allow", "continue": true}'
    return "{}"


# @TOKENS@ are substituted by wrapper_text — plain str.replace, not
# .format(), so the template's own braces (the JSON literal in the
# startswith check) need no escaping.
_STUB_TEMPLATE = '''\
#!/usr/bin/env python3
# @MARK@ — do not edit. Regenerated by `swe init` / `swe hooks sync`.
# Shared source: @SHARED_PATH@
import os
import subprocess
import sys

_RUNTIME = @RUNTIME@
_CONTRACT = @CONTRACT@
_SHARED = @SHARED@
_DEFAULT = @DEFAULT@


def _fallback():
    if _DEFAULT:
        sys.stdout.write(_DEFAULT + "\\n")
    sys.exit(0)


def main():
    raw_text = sys.stdin.read()
    if not (os.path.isfile(_RUNTIME) and os.path.isfile(_SHARED)):
        _fallback()
    try:
        proc = subprocess.run(
            [sys.executable, _RUNTIME, "--contract", _CONTRACT, "--",
             _SHARED] + sys.argv[1:],
            input=raw_text, capture_output=True, text=True, close_fds=True)
    except Exception:
        _fallback()
    if proc.stderr:
        sys.stderr.write(proc.stderr)
    out = proc.stdout
    if proc.returncode == 0 and _DEFAULT and not out.strip().startswith("{"):
        # The contract must answer with JSON; a script that answered with
        # nothing valid still must not stall the session.
        out = _DEFAULT + "\\n"
    sys.stdout.write(out)
    sys.exit(proc.returncode)


main()
'''


def wrapper_text(
    source: Path, harness: str, contract: HookContract, home: Path
) -> str:
    """One generated stub's contents, fully baked for its harness."""
    return (
        _STUB_TEMPLATE
        .replace("@MARK@", GENERATED_MARK)
        .replace("@SHARED_PATH@", str(source))
        .replace("@RUNTIME@", repr(str(runtime_file(home))))
        .replace("@CONTRACT@", repr(_contract_json(harness, contract)))
        .replace("@SHARED@", repr(str(source)))
        .replace("@DEFAULT@", repr(_stub_default(contract)))
    )


def _is_generated(path: Path) -> bool:
    """Whether ``path`` carries our GENERATED marker in its head."""
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            head = "".join(handle.readline() for _ in range(6))
    except OSError:
        return False
    return GENERATED_MARK in head


def _would_write(path: Path, text: str) -> bool:
    """The ``_write_if_changed`` decision, for ``pending_deploy``."""
    try:
        if not path.is_symlink() \
                and path.read_text(encoding="utf-8") == text \
                and os.access(path, os.X_OK):
            return False
    except OSError:
        pass
    return True


def _write_if_changed(path: Path, text: str, home: Path) -> bool:
    """Write ``text`` executable when it differs; True when it wrote.

    A path already holding content that is not ours (no GENERATED mark)
    or a symlink — which ``write_text`` would follow into somebody else's
    file — is preserved into the backups dir before the name is taken,
    the same rule ``swe init`` keeps for destinations. The write lands
    atomically via ``os.replace``, so a hook starting mid-sync reads the
    old file or the new one, never a half-written script.
    """
    if not _would_write(path, text):
        return False
    if path.is_symlink() or (path.exists() and not _is_generated(path)):
        _paths.backup_tree(path, home)
        if path.is_dir() and not path.is_symlink():
            shutil.rmtree(path)
        else:
            path.unlink()
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(tmp, 0o755)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    return True


def _stale_wrappers(
    home: Path, registry: dict, wanted: set[Path]
) -> list[Path]:
    """Generated-marked wrapper files no deploy target wants anymore.

    Archived harnesses are unmanaged everywhere else, so their
    ``_generated`` dirs are skipped here too: archiving a harness must
    not delete the wrappers a destination link still points at.
    """
    from quiver.init.layout import archived_names

    archived = archived_names(registry)
    root = _paths.hooks_dir_for(home)
    stale: list[Path] = []
    if not root.is_dir():
        return stale
    for harness_dir in sorted(root.iterdir()):
        if harness_dir.name in archived \
                or harness_dir.name in RESERVED_HUB_DIRS:
            continue
        gdir = harness_dir / GENERATED_DIRNAME
        if not gdir.is_dir() or gdir.is_symlink():
            continue
        for entry in sorted(gdir.iterdir()):
            if entry.is_file() and entry not in wanted \
                    and _is_generated(entry):
                stale.append(entry)
    return stale


def apply_deploy(
    home: Path, registry: dict | None = None
) -> tuple[list[Path], list[Path]]:
    """Write the runtime + stubs and prune stale ones.

    Returns (written, pruned). A wrapper is pruned only when it carries
    the GENERATED marker and is no longer wanted — a file a user dropped
    into ``_generated`` by hand is left alone, and an emptied
    ``_generated`` dir is removed so nothing links a husk.
    """
    from quiver.init.layout import archived_names, load_registry

    if registry is None:
        registry = load_registry(home)
    targets = deploy_targets(home, registry)
    wanted = {target.wrapper for target in targets}
    written: list[Path] = []
    pruned: list[Path] = []

    runtime = runtime_file(home)
    if targets or runtime.exists():
        if _write_if_changed(runtime, runtime_text(), home):
            written.append(runtime)
    for target in targets:
        contract = contract_for(registry, target.harness, home)
        text = wrapper_text(target.source, target.harness, contract, home)
        if _write_if_changed(target.wrapper, text, home):
            written.append(target.wrapper)

    for entry in _stale_wrappers(home, registry, wanted):
        try:
            entry.unlink()
        except OSError:
            continue
        pruned.append(entry)
    # An emptied _generated dir leaves a dangling whole-dir link target.
    archived = archived_names(registry)
    root = _paths.hooks_dir_for(home)
    if root.is_dir():
        for harness_dir in sorted(root.iterdir()):
            if harness_dir.name in archived:
                continue
            try:
                (harness_dir / GENERATED_DIRNAME).rmdir()
            except OSError:
                pass
    return written, pruned


def pending_deploy(home: Path, registry: dict | None = None) -> int:
    """How many generated files ``apply_deploy`` would write or prune.

    ``swe init --check`` previews with this, so it counts the same work
    apply does: a stale runtime or wrapper rewrite, and each marked file
    pruning removes — not only missing paths.
    """
    from quiver.init.layout import load_registry

    if registry is None:
        registry = load_registry(home)
    targets = deploy_targets(home, registry)
    wanted = {target.wrapper for target in targets}
    pending = 0
    runtime = runtime_file(home)
    if targets or runtime.exists():
        pending += _would_write(runtime, runtime_text())
    for target in targets:
        contract = contract_for(registry, target.harness, home)
        pending += _would_write(
            target.wrapper,
            wrapper_text(target.source, target.harness, contract, home))
    pending += len(_stale_wrappers(home, registry, wanted))
    return pending
