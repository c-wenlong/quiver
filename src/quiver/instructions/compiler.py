"""Validated, atomic compilation of the hub's instruction chapters."""

from contextlib import contextmanager
from dataclasses import dataclass
import hashlib
import os
from pathlib import Path
import stat
import tempfile

try:
    import fcntl
except ImportError:
    fcntl = None

from quiver.paths import (
    agents_file_for, cache_dir_for, instructions_dir_for, instructions_index_for,
    quiver_dir_for,
)


class InstructionError(ValueError):
    """The instruction sources or destination cannot safely be compiled."""


def require_supported_platform() -> None:
    """Fail clearly when safe instruction builds are unavailable on this OS."""
    if fcntl is None or any(getattr(os, flag, None) is None
                            for flag in ("O_NOFOLLOW", "O_NONBLOCK")):
        raise InstructionError(
            "Instruction chapters require POSIX file locking and no-follow "
            "file opens (macOS/Linux)")


class _SourcesChanged(Exception):
    pass


GENERATED_MARKER = (
    "<!-- Generated by swe instructions build from AGENTS_MD/index.txt. "
    "Edit the chapters, not this file. -->"
)


@dataclass(frozen=True)
class _Source:
    path: Path
    resolved: Path
    signature: tuple[int, ...]
    data: bytes


def _signature(info: os.stat_result) -> tuple[int, ...]:
    return (info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns,
            info.st_ctime_ns, info.st_mode)


def _read(path: Path, root: Path) -> _Source:
    resolved = path.resolve(strict=True)
    if not resolved.is_relative_to(root):
        raise InstructionError(f"Instruction source escapes AGENTS_MD: {path}")
    if not stat.S_ISREG(resolved.stat().st_mode):
        raise InstructionError(f"Instruction source is not a regular file: {path}")
    descriptor = os.open(resolved, os.O_RDONLY | os.O_NONBLOCK | os.O_NOFOLLOW)
    with os.fdopen(descriptor, "rb") as handle:
        before = os.fstat(handle.fileno())
        if not stat.S_ISREG(before.st_mode):
            raise InstructionError(f"Instruction source is not a regular file: {path}")
        data = handle.read()
        after = os.fstat(handle.fileno())
    if (_signature(before) != _signature(after)
            or _signature(path.stat()) != _signature(after)
            or path.resolve(strict=True) != resolved):
        raise _SourcesChanged
    return _Source(path, resolved, _signature(after), data)


def _text(source: _Source) -> str:
    try:
        return source.data.decode("utf-8")
    except UnicodeError as exc:
        raise InstructionError(f"Instruction source is not UTF-8: {source.path}") from exc


def _snapshot(home: Path | None) -> tuple[tuple[_Source, ...], bytes]:
    directory = instructions_dir_for(home)
    root = directory.resolve(strict=True)
    hub = quiver_dir_for(home).resolve()
    if root == hub or not root.is_relative_to(hub):
        raise InstructionError(f"Instruction directory escapes the hub: {directory}")
    index = _read(instructions_index_for(home), root)
    sources = [index]
    seen: set[Path] = set()
    parts = [GENERATED_MARKER + "\n\n"]
    for number, line in enumerate(_text(index).splitlines(), 1):
        name = line.strip()
        if not name or name.startswith("#"):
            continue
        relative = Path(name)
        if (relative.is_absolute() or relative.suffix.lower() != ".md"
                or any(character in name for character in ("\x00", "\r", "\n"))
                or "-->" in name):
            raise InstructionError(f"Invalid chapter at index.txt:{number}: {name!r}")
        source = _read(directory / relative, root)
        if source.resolved in seen:
            raise InstructionError(f"Duplicate instruction chapter: {name}")
        seen.add(source.resolved)
        sources.append(source)
        parts.append(f"<!-- Source: AGENTS_MD/{relative.as_posix()} -->\n")
        text = _text(source)
        parts.append(text)
        if not text.endswith("\n"):
            parts.append("\n")
        parts.append("\n")
    if len(sources) == 1:
        raise InstructionError("AGENTS_MD/index.txt contains no instruction chapters")
    return tuple(sources), ("".join(parts).rstrip("\n") + "\n").encode("utf-8")


def _unchanged(sources: tuple[_Source, ...], root: Path) -> bool:
    return all(_read(source.path, root) == source
               for source in sources)


def source_fingerprint(home: Path | None = None) -> bytes:
    """Fingerprint the index and its listed sources, including invalid states.

    Missing or invalid sources have a stable error fingerprint. Polling retries
    validation, so fixing an index, chapter or symlink changes that fingerprint
    without requiring a recursive scan of unrelated files.
    """
    digest = hashlib.sha256()
    try:
        require_supported_platform()
        sources, _ = _snapshot(home)
    except (InstructionError, OSError, RuntimeError, _SourcesChanged) as exc:
        digest.update(repr((type(exc).__name__, str(exc))).encode("utf-8"))
    else:
        for source in sources:
            digest.update(repr((str(source.path), str(source.resolved),
                                source.signature)).encode("utf-8"))
            digest.update(hashlib.sha256(source.data).digest())
    return digest.digest()


_SOURCE_MARKER = "<!-- Source: AGENTS_MD/"

_UNSET = object()


def _output(path: Path) -> tuple[bytes | None, int]:
    try:
        info = path.lstat()
    except FileNotFoundError:
        return None, 0o644
    if stat.S_ISLNK(info.st_mode):
        raise InstructionError(f"Refusing to replace a symlink: {path}")
    if not stat.S_ISREG(info.st_mode):
        raise InstructionError(f"Instruction output is not a regular file: {path}")
    # O_NOFOLLOW also rejects a symlink substituted after lstat.
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(descriptor, "rb") as handle:
        return handle.read(), stat.S_IMODE(os.fstat(handle.fileno()).st_mode)


@contextmanager
def _locked(home: Path | None):
    directory = cache_dir_for(home)
    directory.mkdir(parents=True, exist_ok=True)
    with (directory / "instructions.lock").open("a+b") as lock:
        fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(lock.fileno(), fcntl.LOCK_UN)


def _build(home: Path | None, check: bool, expected=_UNSET) -> bool:
    output = agents_file_for(home)
    for _ in range(3):
        temporary: str | None = None
        try:
            sources, data = _snapshot(home)
            previous, mode = _output(output)
            if expected is not _UNSET and previous != expected:
                raise InstructionError(
                    f"{output} changed while its chapters were being created; "
                    "not overwriting it")
            differs = previous is None or hashlib.sha256(previous).digest() != hashlib.sha256(data).digest()
            if check or not differs:
                if _unchanged(sources, instructions_dir_for(home).resolve()):
                    return differs
                continue
            descriptor, temporary = tempfile.mkstemp(
                dir=output.parent, prefix=".AGENTS.md.", suffix=".tmp")
            with os.fdopen(descriptor, "wb") as handle:
                handle.write(data)
                handle.flush()
                os.fchmod(handle.fileno(), mode)
                os.fsync(handle.fileno())
            if not _unchanged(sources, instructions_dir_for(home).resolve()):
                continue
            latest, _ = _output(output)  # Refuse aliases introduced while the sources were read.
            if expected is not _UNSET and latest != expected:
                raise InstructionError(
                    f"{output} changed while its chapters were being created; "
                    "not overwriting it")
            os.replace(temporary, output)
            return True
        except _SourcesChanged:
            continue
        finally:
            if temporary is not None:
                try:
                    os.unlink(temporary)
                except FileNotFoundError:
                    pass
    raise InstructionError("Instruction sources kept changing; try the build again")


def build(home: Path | None = None, *, check: bool = False, expected=_UNSET) -> bool:
    """Return whether AGENTS.md differs, replacing it unless ``check`` is set.

    Writing builds serialize through a hub-local lock. Every source is reread before
    replacement; a source edited during compilation causes a fresh attempt.
    Identical output keeps its inode, timestamps and permissions unchanged.

    ``expected`` pins the output's bytes (None pins its absence), for callers
    that fold the file's current content into sources and must not overwrite a
    save that landed meanwhile; the default is no expectation.
    """
    require_supported_platform()
    try:
        if check:
            return _build(home, check=True)
        with _locked(home):
            return _build(home, check, expected)
    except (OSError, RuntimeError) as exc:
        raise InstructionError(f"Cannot compile instructions: {exc}") from exc


def chapter_names(home: Path | None = None) -> list[str]:
    """The chapter paths index.txt lists, in order, forgiving its mistakes.

    This is a read for display: blank lines and ``#`` comments are skipped,
    and an entry the stricter build-time validation would reject is still
    returned so a caller can show it. ``build`` stays the authority on what
    compiles.
    """
    index = instructions_index_for(home)
    try:
        text = index.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        return []
    return [line.strip() for line in text.splitlines()
            if line.strip() and not line.strip().startswith("#")]


def survey(home: Path | None = None) -> dict:
    """The ``swe instructions check --json`` document.

    ``stale`` is None when chapters are not set up at all (``index_exists``
    is then false), which plain ``check`` reports as an error instead: the
    app needs the distinction to pick the chapter editor or the flat one.
    """
    directory = instructions_dir_for(home)
    index = instructions_index_for(home)
    output = agents_file_for(home)
    index_exists = index.is_file()
    output_exists = output.is_file()
    generated = False
    if output_exists:
        try:
            with output.open("r", encoding="utf-8", errors="replace") as handle:
                generated = GENERATED_MARKER in handle.readline()
        except OSError:
            pass
    stale: bool | None = None
    error: str | None = None
    if index_exists:
        try:
            stale = build(home, check=True)
        except InstructionError as exc:
            error = str(exc)
    return {
        "directory": str(directory),
        "index": str(index),
        "output": str(output),
        "index_exists": index_exists,
        "output_exists": output_exists,
        "output_generated": generated,
        "chapters": [
            {"name": name, "path": str(directory / name),
             "exists": (directory / name).is_file()}
            for name in chapter_names(home)
        ],
        "error": error,
        "stale": stale,
    }


def init_sources(home: Path | None = None) -> dict:
    """Fold the current AGENTS.md into one chapter, then build.

    ``init`` is idempotent in intent but not silent: when index.txt already
    exists there is nothing to fold, so it refuses rather than touching a
    working setup. A generated AGENTS.md without an index has its compiler
    comments stripped back out, leaving real text as the chapter.
    """
    require_supported_platform()
    directory = instructions_dir_for(home)
    index = instructions_index_for(home)
    if index.exists() or index.is_symlink():
        raise InstructionError(
            f"{index} already exists; chapters are already set up")
    if directory.is_symlink():
        raise InstructionError(f"Refusing to use a symlinked directory: {directory}")

    output = agents_file_for(home)
    # Refuses a symlinked or non-file destination before any source is
    # created, so a failed conversion cannot leave chapter mode half-set.
    previous, _ = _output(output)
    text = "# Instructions\n\nShared rules every harness reads.\n"
    source = "a starter chapter"
    if previous is not None:
        try:
            raw = previous.decode("utf-8")
        except UnicodeError as exc:
            raise InstructionError(f"{output} is not UTF-8 text") from exc
        if GENERATED_MARKER in raw.split("\n", 1)[0]:
            # Only the compiler's own comment lines come back out; one-line
            # HTML comments in chapter content are the user's, and stay.
            raw = "\n".join(
                line for line in raw.splitlines()
                if line != GENERATED_MARKER
                and not (line.startswith(_SOURCE_MARKER) and line.endswith("-->")))
        raw = raw.strip("\n")
        if raw:
            text = raw + "\n"
            source = str(output)
    directory.mkdir(parents=True, exist_ok=True)

    name = "main.md"
    counter = 2
    while (directory / name).exists():
        name = f"main-{counter}.md"
        counter += 1
    try:
        with (directory / name).open("x", encoding="utf-8") as handle:
            handle.write(text)
        with index.open("x", encoding="utf-8") as handle:
            handle.write(
                "# Chapters, in order. One relative .md path per line.\n"
                f"{name}\n")
    except OSError as exc:
        raise InstructionError(f"Cannot create chapters in {directory}: {exc}") from exc
    # The build overwrites the output; it must be the bytes just folded, not
    # a save that landed meanwhile.
    return {"created": True, "chapter": name, "source": source,
            "built": build(home, expected=previous)}
