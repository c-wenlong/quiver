"""Strip harness-injected context from chat messages before they reach a client.

Harnesses write things into the transcript that their own UI never shows
as chat: Claude Code's ``<system-reminder>`` and ``<task-notification>``
envelopes, Cursor's ``<timestamp>``/``<user_query>`` wrapper, Codex's
AGENTS.md and environment injections and its ``<oai-mem-citation>``
footer. Left in, they read as raw XML on the phone (a scan of the 8
newest sessions per harness found them on every Cursor prompt and most
Claude Code ones). ``clean`` maps one ``protocol.message`` payload to
what a person should see: the same message tidied, a short ``system``
line, or None to drop it.
"""

from __future__ import annotations

import re

# Blocks removed wherever they appear, contents and all.
_STRIP_BLOCKS = (
    "system-reminder",
    "oai-mem-citation",
    "timestamp",
    "local-command-caveat",
    "codex_apps_client_time_context",
    "codex_apps_open_page_instructions",
    "external_codex_apps_open_page",
    "skills_instructions",
    "collaboration_mode",
    "multi_agent_mode",
    "multi_agent_role",
    "environment_context",
    "user_instructions",
    "in-app-browser-context",
    "available_subagent_types",
    "available_subagent_models",
    "dynamic_tools",
    "dynamic_tool_namespaces",
    "hooks_context",
)
# Agent text keeps everything it wrote except Codex's memory footer: an
# agent can legitimately quote any of the tags above.
_AGENT_STRIP_BLOCKS = ("oai-mem-citation",)


def _strip_re(tags: tuple[str, ...]) -> re.Pattern[str]:
    return re.compile(
        r"<(?P<tag>" + "|".join(re.escape(t) for t in tags) + r")(?:\s[^>]*)?>.*?</(?P=tag)>",
        re.S,
    )


_STRIP_RE = _strip_re(_STRIP_BLOCKS)
_AGENT_STRIP_RE = _strip_re(_AGENT_STRIP_BLOCKS)

# A whole message that is only an instruction injection.
_INJECTED_PREFIXES = (
    "# AGENTS.md instructions for",
    "<INSTRUCTIONS>",
    "Caveat: The messages below were generated by the user while running local commands.",
)


def _inner(tag: str, text: str) -> str | None:
    m = re.search(rf"<{re.escape(tag)}(?:\s[^>]*)?>(.*?)</{re.escape(tag)}>", text, re.S)
    return m.group(1).strip() if m else None


# Marks a message this module rewrote. The hub cleans twice (when it
# decodes, then again when it serves, for journals written before this
# module), and a rewrite is not always idempotent: an unwrapped Cursor
# query can itself start with an injected prefix.
CLEANED = "cleaned"

# Codex developer turns that older journals stored as agent text, before
# the decoder learned to drop them. A real reply never opens this way.
_CODEX_DEVELOPER_PREFIXES = (
    "<codex_apps_",
    "<skills_instructions>",
    "<multi_agent_mode>",
    "<multi_agent_role>",
    "<collaboration_mode>",
    "<tools>",
    "<turn_aborted>",
    "<model_switch>",
    "<image_resize_notice>",
    "This is a terminal/Codex session.",
    "Composio is available in this session",
    "## Memory\n\nYou have access to a memory",
    "You are Codex, an agent based on",
    "This is an incremental tools update",
    "You are `/root`, the primary agent",
    "You mentioned a service Composio can",
    "You mentioned an app Composio can",
)


def _rewrite(msg: dict, **changes) -> dict:
    return dict(msg, **changes, **{CLEANED: True})


def _system(msg: dict, text: str) -> dict:
    return _rewrite(msg, kind="system", text=text)


def clean(msg: dict) -> dict | None:
    """The message as a person should see it, or None to drop it."""
    if msg.get(CLEANED):
        return msg
    kind = msg.get("kind")
    text = msg.get("text") or ""
    if kind == "assistant":
        if "<oai-mem-citation" not in text:
            return msg
        cleaned = _AGENT_STRIP_RE.sub("", text).strip()
        return _rewrite(msg, text=cleaned) if cleaned else None
    if kind not in ("user", "system"):
        return msg
    stripped = text.lstrip()
    if not stripped.startswith(("<", "#", "Caveat")) and "<system-reminder>" not in text:
        return msg

    if kind == "user" and stripped.startswith(_INJECTED_PREFIXES):
        return None
    # Injected blocks go first: a harness can stack them ahead of the
    # envelope (a reminder, then a side-sessions note).
    text = _STRIP_RE.sub("", text).strip()
    stripped = text
    if not text:
        return None

    # The envelopes below are recognised only at the start of the
    # message, so a prompt that merely mentions one stays as typed.
    # Claude Code background task finished: one quiet line.
    if stripped.startswith("<task-notification>"):
        summary = _inner("summary", text) or "Background task finished"
        status = _inner("status", text)
        line = summary if not status or status in summary else f"{summary} ({status})"
        return _system(msg, line)

    # The desktop app's CI monitor and side-session notes: name them,
    # keep the first sentence.
    for tag, label in (("ci-monitor-event", "CI monitor"), ("side-sessions-event", "Side sessions")):
        if stripped.startswith(f"<{tag}>"):
            body = re.sub(r"\s+", " ", _inner(tag, text) or "").strip()
            first = re.split(r"(?<=[.!?])\s", body, maxsplit=1)[0] if body else ""
            return _system(msg, f"{label}: {first}"[:200] if first else label)

    # A slash command: show what was typed.
    name = _inner("command-name", text) if stripped.startswith(("<command-", "<command-name")) else None
    if name is not None:
        args = _inner("command-args", text) or ""
        return _rewrite(msg, text=f"{name} {args}".strip())
    out = _inner("local-command-stdout", text) if stripped.startswith("<local-command-stdout") else None
    if out is not None:
        return _system(msg, out) if out else None

    # Cursor wraps every prompt: keep only the query.
    query = _inner("user_query", text) if stripped.startswith("<user_query") else None
    if query is not None:
        text = query
    if not text:
        return None
    if text == (msg.get("text") or ""):
        return msg
    return _rewrite(msg, text=text)


def clean_all(messages: list[dict]) -> list[dict]:
    return [m for m in (clean(x) for x in messages) if m is not None]


def clean_event(ev: dict) -> dict | None:
    """A journal event as served: message events are cleaned (journals
    written before this module still hold the raw text), others pass."""
    if ev.get("type") != "message.appended" or not isinstance(ev.get("data"), dict):
        return ev
    raw = ev["data"]
    if (str(ev.get("session") or "").startswith("codex:") and raw.get("kind") == "assistant"
            and (raw.get("text") or "").lstrip().startswith(_CODEX_DEVELOPER_PREFIXES)):
        return None
    data = clean(raw)
    if data is None:
        return None
    return ev if data is ev["data"] else dict(ev, data=data)
