import Foundation

/// Orca's `isKnownHarnessInjectedUserTurnText` (`harness-injected-user-turns.ts`):
/// machinery turns a harness writes under the `user` role — task
/// notifications, system reminders, command envelopes — matched only by
/// observed tag names and delivery prefixes on the trimmed, lowercased head.
/// Unknown kebab tags stay user turns: a real prompt opening `<my-element>`
/// must not be demoted.
enum SearchInjectedTurn {
    /// The observed tag names (Orca's `KNOWN_HARNESS_TAG_NAMES`).
    static let tagNames: Set<String> = [
        "agent-message", "bash-input", "bash-stderr", "bash-stdout",
        "command-args", "command-message", "command-name",
        "cross-session-message", "fork-boilerplate", "local-command-caveat",
        "local-command-stderr", "local-command-stdout", "mcp-polling-update",
        "mcp-resource-update", "system-reminder", "task-notification",
        "teammate-message", "user-memory-input", "user-prompt-submit-hook",
    ]

    /// The observed prose prefixes (Orca's `HARNESS_INJECTED_TURN_PREFIXES`).
    static let prefixes = [
        "<channel source=",
        "[request interrupted",
        "a message arrived from ",
        "another claude session sent a message",
        "no response requested.",
        "caveat: the messages below were generated by the user while running local commands",
        "this session is being continued from a previous conversation",
    ]

    static func isKnown(_ text: String) -> Bool {
        let head = normalizedHead(text)
        guard !head.isEmpty else { return false }
        if let tag = leadingTagName(head), tagNames.contains(tag) { return true }
        return prefixes.contains(where: { head.hasPrefix($0) })
    }

    /// Orca's `normalizedHarnessTurnHead`: skip ≤64 leading ASCII whitespace
    /// units, take ≤256 UTF-16 units, lowercase — classification stays O(1)
    /// on multi-KB pastes.
    private static func normalizedHead(_ text: String) -> String {
        let utf16 = Array(text.utf16)
        var start = 0
        while start < min(utf16.count, 64), isASCIIWhitespace(utf16[start]) {
            start += 1
        }
        guard start < utf16.count else { return "" }
        return String(decoding: utf16[start..<min(utf16.count, start + 256)], as: UTF16.self)
            .lowercased()
    }

    private static func isASCIIWhitespace(_ unit: UInt16) -> Bool {
        unit == 0x09 || unit == 0x0A || unit == 0x0B || unit == 0x0C || unit == 0x0D
            || unit == 0x20
    }

    /// The leading `<name>` of a lowercase head — Orca's
    /// `/^<([a-z][a-z0-9-]*)(?:[\s>]|$)/`.
    private static func leadingTagName(_ head: String) -> String? {
        guard head.hasPrefix("<") else { return nil }
        var name = ""
        for scalar in head.dropFirst() {
            if scalar == ">" || scalar.isWhitespace { break }
            guard scalar.isASCII, scalar.isLetter || scalar.isNumber || scalar == "-"
            else { return nil }
            name.append(scalar)
        }
        guard let first = name.first, first.isASCII, first.isLetter else { return nil }
        return name
    }
}

/// Orca's `extractContentText` for injected-turn checks: a string, or the
/// `text`/`content` of a block array, folded to one whitespace-normalized
/// line capped at the 96-unit title width.
func searchNormalizedContentText(_ content: Any?) -> String? {
    if let string = content as? String {
        return SearchText.titleCandidate(string, limit: 96)
    }
    guard let array = content as? [Any] else { return nil }
    var parts: [String] = []
    for item in array {
        guard let text = (item as? String)
            ?? (item as? [String: Any]).flatMap({ ($0["text"] ?? $0["content"]) as? String })
        else { continue }
        parts.append(text)
    }
    return SearchText.titleCandidate(parts.joined(separator: " "), limit: 96)
}

/// Qoder `~/.qoder/projects/**/*.jsonl`: Qoder 1.1.64 shares Claude's record
/// shapes plus startup records (Orca's `consumeQoderLine`). `message.content`
/// arrays are filtered to `text` blocks before the Claude decode runs — tool
/// blocks never reach the preview or the index — `workspace-directories`
/// supplies the cwd when no earlier record carried one (`updateLatestLocation`
/// keeps the session's start cwd), and `runtime-config` only restates the
/// model.
struct SearchQoderDecoder {
    struct State: Codable, Equatable, Sendable {
        /// Orca's `updateLatestLocation`: the first cwd wins, so it emits once.
        var cwdEmitted = false
    }

    var state = State()

    /// Qoder writes `"type": "x"` with a space; the markers cover both
    /// spacings since fixtures and resumed sessions have been seen compact.
    static let markers = [
        #""type":"user""#, #""type":"assistant""#, #""type": "user""#, #""type": "assistant""#,
        #""custom-title""#, #""ai-title""#, #""workspace-directories""#,
    ].map { Data($0.utf8) }

    mutating func decode(object: [String: Any]) -> (messages: [SearchMessage], hints: SearchHints) {
        var filtered = object
        if let message = object["message"] as? [String: Any],
           let content = message["content"] as? [Any] {
            var trimmed = message
            trimmed["content"] = content.filter {
                ($0 as? [String: Any])?["type"] as? String == "text"
            }
            filtered["message"] = trimmed
        }
        var output = SearchClaudeDecoder.decode(object: filtered)
        // `updateLatestLocation`: only the first cwd counts — restatement is
        // noise, so the emit happens once here instead.
        if output.hints.cwd != nil {
            if state.cwdEmitted {
                output.hints.cwd = nil
            } else {
                state.cwdEmitted = true
            }
        }
        if object["type"] as? String == "workspace-directories", !state.cwdEmitted,
           let directories = object["directories"] as? [Any],
           let cwd = directories.first.flatMap({ JSONValue.string($0) }) {
            output.hints.cwd = cwd
            state.cwdEmitted = true
        }
        return output
    }
}

/// CodeBuddy `~/.codebuddy/projects/**/*.jsonl` (Orca's
/// `consumeCodebuddySessionLine`): flat `sessionId`/`cwd`/`gitBranch`,
/// `type` `summary` and `ai-title` are the CLI's session titles, and `type`
/// `message` records hold top-level `role` + `content` text-block arrays
/// (`input_text`/`output_text`/`text` joined by a blank line). Meta user
/// turns — `providerData.skipRun` or a known injected-turn tag — index as
/// user messages but never seed the title.
///
/// Orca's title order — `summary` > `ai-title` > first real user text —
/// holds because `summary` re-emits (latest wins), `ai-title` is suppressed
/// once a summary landed, and the prompt candidate only seeds while no
/// explicit title has been seen.
struct SearchCodebuddyDecoder {
    struct State: Codable, Equatable, Sendable {
        /// `updateLatestLocation`: the session's start cwd, emitted once.
        var cwdEmitted = false
        /// Set when a `summary` record landed — it outranks `ai-title` for good.
        var sawSummaryTitle = false
    }

    var state = State()

    static let markers = [
        #""message""#, #""summary""#, #""ai-title""#, #""sessionId""#, #""cwd""#,
        #""gitBranch""#,
    ].map { Data($0.utf8) }

    mutating func decode(object: [String: Any]) -> (messages: [SearchMessage], hints: SearchHints) {
        var hints = SearchHints()
        hints.sessionId = JSONValue.string(object["sessionId"])
        if !state.cwdEmitted, let cwd = JSONValue.string(object["cwd"]) {
            hints.cwd = cwd
            state.cwdEmitted = true
        }
        hints.branch = JSONValue.string(object["gitBranch"])
        let ts = SearchStamp.iso(object["timestamp"])
        switch object["type"] as? String {
        case "summary":
            if let title = JSONValue.string(object["summary"])
                .flatMap({ SearchText.titleCandidate($0, limit: 96) }) {
                hints.title = title
                state.sawSummaryTitle = true
            }
        case "ai-title":
            if !state.sawSummaryTitle,
               let title = JSONValue.string(object["aiTitle"])
                .flatMap({ SearchText.titleCandidate($0, limit: 96) }) {
                hints.title = title
            }
        case "message":
            let role = JSONValue.string(object["role"])
            guard let text = SearchText.bounded(Self.contentText(object["content"]) ?? "")
            else { return ([], hints) }
            if role == "user" {
                hints.injectedUserTurn =
                    (object["providerData"] as? [String: Any])?["skipRun"] as? Bool == true
                    || SearchInjectedTurn.isKnown(text)
                return ([SearchMessage(role: .user, text: text, ts: ts)], hints)
            }
            if role == "assistant" {
                return ([SearchMessage(role: .assistant, text: text, ts: ts)], hints)
            }
        default:
            break
        }
        return ([], hints)
    }

    /// Orca's `codebuddyContentText`: a string is the text; an array keeps
    /// the `input_text`/`output_text`/`text` blocks' text joined by a blank
    /// line.
    static func contentText(_ content: Any?) -> String? {
        if let string = content as? String { return string }
        guard let array = content as? [Any] else { return nil }
        let parts = array.compactMap { block -> String? in
            guard let record = block as? [String: Any],
                  ["input_text", "output_text", "text"].contains(JSONValue.string(record["type"]))
            else { return nil }
            return JSONValue.string(record["text"])
        }
        return parts.isEmpty ? nil : parts.joined(separator: "\n\n")
    }
}

/// GitHub Copilot `~/.copilot/session-state/*.jsonl` (Orca's
/// `consumeCopilotRecordLine`): `session.start` carries the id,
/// `session.info` `folder_trust` messages carry the cwd ("Folder <path> has
/// been added to trusted folders."), and `user.message`/`assistant.message`
/// records hold `data.transformedContent`/`data.content` text.
/// `session.model_change`/`session.shutdown` fields SWE cannot model are
/// skipped.
enum SearchCopilotDecoder {
    static let markers = [
        #""session.start""#, #""session.info""#, #""user.message""#, #""assistant.message""#,
    ].map { Data($0.utf8) }

    static func decode(object: [String: Any]) -> (messages: [SearchMessage], hints: SearchHints) {
        var hints = SearchHints()
        let data = object["data"] as? [String: Any]
        let ts = SearchStamp.iso(object["timestamp"])
        switch object["type"] as? String {
        case "session.start":
            hints.sessionId = JSONValue.string(data?["sessionId"])
        case "session.info":
            hints.cwd = trustedFolder(JSONValue.string(data?["message"]))
        case "user.message":
            guard let text = SearchText.bounded(
                JSONValue.string(data?["transformedContent"])
                    ?? JSONValue.string(data?["content"]) ?? "")
            else { return ([], hints) }
            return ([SearchMessage(role: .user, text: text, ts: ts)], hints)
        case "assistant.message":
            guard let text = SearchText.bounded(JSONValue.string(data?["content"]) ?? "")
            else { return ([], hints) }
            return ([SearchMessage(role: .assistant, text: text, ts: ts)], hints)
        default:
            break
        }
        return ([], hints)
    }

    /// Orca's `extractTrustedFolder`: `Folder <path> has been added to
    /// trusted folders.` → `<path>`.
    private static func trustedFolder(_ message: String?) -> String? {
        let prefix = "Folder ", suffix = " has been added to trusted folders."
        guard let message, message.hasPrefix(prefix), message.hasSuffix(suffix),
              message.count > prefix.count + suffix.count
        else { return nil }
        return String(message.dropFirst(prefix.count).dropLast(suffix.count))
    }
}

/// Hermes `~/.hermes/sessions/session_*.json` — one whole document (Orca's
/// `parseHermesSessionFile`): `session_id`, `model`, `cwd`,
/// `session_start`/`last_updated` timeline, and `messages[]` `{role,
/// content}` user/assistant turns through `SearchContent`. Messages carry
/// no per-record timestamp.
enum SearchHermesDecoder {
    static let markers = [
        #""session_id""#, #""messages""#, #""cwd""#, #""session_start""#,
    ].map { Data($0.utf8) }

    static func decode(object: [String: Any]) -> (messages: [SearchMessage], hints: SearchHints) {
        var hints = SearchHints()
        hints.sessionId = JSONValue.string(object["session_id"])
        hints.cwd = JSONValue.string(object["cwd"])
        var messages: [SearchMessage] = []
        for value in object["messages"] as? [Any] ?? [] {
            guard let record = value as? [String: Any],
                  let role = record["role"] as? String,
                  role == "user" || role == "assistant"
            else { continue }
            messages += SearchContent.messages(
                role: role == "user" ? .user : .assistant,
                content: record["content"], ts: nil)
        }
        return (messages, hints)
    }
}

/// JCode `~/.jcode/sessions/session_*.json` — one whole document (Orca's
/// `parseJcodeSessionContent`): `id`/`session_id`, `custom_title` then
/// `title` for the explicit title, `working_dir`/`working_directory`, and
/// `messages[]` `{role, display_role, content, timestamp}`. Injected context
/// is dropped (`isInjectedContextMessage`): `display_role` `system`/
/// `background_task`, `role` `system`, or text opening `[Scheduled task]`/
/// `<system-reminder>`. Roles map user/assistant/tool verbatim
/// (`PREVIEW_ROLE_BY_MESSAGE_ROLE`); other roles publish tool blocks only.
enum SearchJcodeDecoder {
    static let markers = [
        #""session_id""#, #""messages""#, #""custom_title""#, #""title""#,
        #""working_dir""#, #""id""#,
    ].map { Data($0.utf8) }

    static func decode(object: [String: Any]) -> (messages: [SearchMessage], hints: SearchHints) {
        var hints = SearchHints()
        hints.sessionId = JSONValue.string(object["id"]) ?? JSONValue.string(object["session_id"])
        hints.cwd = JSONValue.string(object["working_dir"])
            ?? JSONValue.string(object["working_directory"])
        hints.title = JSONValue.string(object["custom_title"])
            .flatMap { SearchText.titleCandidate($0, limit: 96) }
            ?? JSONValue.string(object["title"])
            .flatMap { SearchText.titleCandidate($0, limit: 96) }
        var messages: [SearchMessage] = []
        for value in object["messages"] as? [Any] ?? [] {
            guard let record = value as? [String: Any], !isInjectedContext(record)
            else { continue }
            let role: SearchRole? = switch record["role"] as? String {
            case "user": .user
            case "assistant": .assistant
            case "tool": .tool
            default: nil
            }
            messages += SearchContent.messages(
                role: role, content: record["content"],
                ts: SearchStamp.iso(record["timestamp"]))
        }
        return (messages, hints)
    }

    /// Orca's `isInjectedContextMessage` — jcode's own "internal" rows, not
    /// conversation.
    private static func isInjectedContext(_ message: [String: Any]) -> Bool {
        let displayRole = message["display_role"] as? String
        if displayRole == "system" || displayRole == "background_task" { return true }
        if message["role"] as? String == "system" { return true }
        let text = searchNormalizedContentText(message["content"]) ?? ""
        return text.hasPrefix("[Scheduled task]") || text.hasPrefix("<system-reminder>")
    }
}

/// Muse `<root>/YYYY/MM/DD/<uuid>/session.jsonl` (Orca's
/// `session-scanner-muse-parser.ts`): one log line is an envelope
/// `{record_type, payload_type, recorded_at, payload}` — `recorded_at` is
/// epoch microseconds — or a `retained_frame` batching real records inside
/// `children[].record_json` strings (`unwrapMuseLogRecords`). Payload types:
/// `runtime.session.metadata`/`runtime.session.route_facts` carry the first
/// cwd, `session.workspace_branch.observed` the first branch,
/// `runtime.user_intent.accepted` a user turn (`refill_blocks` or
/// `model_messages[].content` text blocks), and `runtime.session` run
/// events — `started` is the same prompt ~ms later and dedupes within 60s,
/// `assistant_message_committed` the assistant turn.
struct SearchMuseDecoder {
    struct State: Codable, Equatable, Sendable {
        /// Last folded user turn, for the `run.started` 60s dedupe.
        var dedupeText: String?
        var dedupeMs: Double?
        /// `??=` semantics: the first cwd and branch win.
        var cwdEmitted = false
        var branchEmitted = false
    }

    var state = State()

    static let markers = [
        #""payload_type""#, #""recorded_at""#, #""children""#, #""record_json""#,
    ].map { Data($0.utf8) }

    mutating func decode(object: [String: Any]) -> (messages: [SearchMessage], hints: SearchHints) {
        var messages: [SearchMessage] = []
        var hints = SearchHints()
        for record in Self.unwrap(object) {
            fold(record, messages: &messages, hints: &hints)
        }
        return (messages, hints)
    }

    /// Orca's `unwrapMuseLogRecords`: a `children` array means the line is a
    /// retained frame and its `record_json` strings are the records;
    /// anything else stands alone.
    private static func unwrap(_ envelope: [String: Any]) -> [[String: Any]] {
        guard let children = envelope["children"] as? [Any] else { return [envelope] }
        var records: [[String: Any]] = []
        for child in children {
            guard let raw = (child as? [String: Any])?["record_json"] else { continue }
            let parsed: Any? = (raw as? String).flatMap {
                try? JSONSerialization.jsonObject(with: Data($0.utf8))
            } ?? raw
            if let record = parsed as? [String: Any] { records.append(record) }
        }
        return records
    }

    /// Orca's `foldMuseRecord`.
    private mutating func fold(
        _ record: [String: Any], messages: inout [SearchMessage], hints: inout SearchHints
    ) {
        let ms = Self.timestampMs(record["recorded_at"])
        let ts = ms.flatMap { SearchStamp.iso($0) }
        guard let payload = record["payload"] as? [String: Any] else { return }
        switch JSONValue.string(record["payload_type"]) {
        case "runtime.session.metadata":
            if !state.cwdEmitted,
               let cwd = JSONValue.string(
                    (payload["record"] as? [String: Any])?["workspace_root"]) {
                hints.cwd = cwd
                state.cwdEmitted = true
            }
        case "runtime.session.route_facts":
            if !state.cwdEmitted,
               let cwd = JSONValue.string((payload["record"] as? [String: Any])?["cwd"]) {
                hints.cwd = cwd
                state.cwdEmitted = true
            }
        case "session.workspace_branch.observed":
            let reference = (payload["record"] as? [String: Any])?["reference"] as? [String: Any]
            if !state.branchEmitted, let branch = JSONValue.string(reference?["name"]) {
                hints.branch = branch
                state.branchEmitted = true
            }
        case "runtime.user_intent.accepted":
            foldUserTurn(Self.userIntentText(payload), ts: ts, ms: ms,
                         dedupe: false, messages: &messages)
        case "runtime.session":
            guard let event = payload["event"] as? [String: Any] else { return }
            switch event["kind"] as? String {
            case "started":
                foldUserTurn(JSONValue.string(event["prompt"]), ts: ts, ms: ms,
                             dedupe: true, messages: &messages)
            case "assistant_message_committed":
                if let text = SearchText.bounded(JSONValue.string(event["text"]) ?? "") {
                    messages.append(SearchMessage(role: .assistant, text: text, ts: ts))
                }
            default:
                break
            }
        default:
            break
        }
    }

    /// Orca's `foldUserTurn`: `run.started` carrying the intent's prompt
    /// ~ms later dedupes within 60s; the intent record itself never does.
    private mutating func foldUserTurn(
        _ text: String?, ts: String?, ms: Double?, dedupe: Bool,
        messages: inout [SearchMessage]
    ) {
        guard let text, let bounded = SearchText.bounded(text) else { return }
        if dedupe, state.dedupeText == text, let lastMs = state.dedupeMs, let ms,
           abs(ms - lastMs) < 60_000 {
            return
        }
        state.dedupeText = text
        state.dedupeMs = ms
        messages.append(SearchMessage(role: .user, text: bounded, ts: ts))
    }

    /// Orca's `userIntentText`: `refill_blocks` text blocks, else the
    /// `model_messages[].content[]` blocks' first text.
    private static func userIntentText(_ payload: [String: Any]) -> String? {
        if let text = firstTextBlock(payload["refill_blocks"]) { return text }
        for message in payload["model_messages"] as? [Any] ?? [] {
            if let text = firstTextBlock((message as? [String: Any])?["content"]) {
                return text
            }
        }
        return nil
    }

    /// The first block's `text` — Orca's `firstTextBlock`.
    private static func firstTextBlock(_ value: Any?) -> String? {
        for block in value as? [Any] ?? [] {
            if let text = JSONValue.string((block as? [String: Any])?["text"]) {
                return text
            }
        }
        return nil
    }

    /// Orca's `museTimestampMs`: `recorded_at` is microseconds (floor 1e14);
    /// anything smaller is the shared seconds/ms/ISO case.
    static func timestampMs(_ value: Any?) -> Double? {
        if let number = value as? NSNumber,
           !(number === kCFBooleanTrue || number === kCFBooleanFalse),
           number.doubleValue.isFinite, number.doubleValue >= 1e14 {
            return (number.doubleValue / 1000).rounded(.down)
        }
        return SearchStamp.milliseconds(value)
    }
}
